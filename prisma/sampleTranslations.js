// sampleData.js のお店に、都市名の訳も含めた translations を足して返す
export function withTranslations(place) {
  const byLang = sampleTranslations[place.name] ?? {};
  const translations = {};
  for (const lang of ['ja', 'zh', 'ko']) {
    const cityName = city[place.city]?.[lang];
    if (byLang[lang] || cityName) translations[lang] = { ...byLang[lang], ...(cityName && { city: cityName }) };
  }
  return { ...place, translations };
}
